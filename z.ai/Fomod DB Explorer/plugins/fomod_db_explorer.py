"""
FOMOD DB Explorer - Mod Organizer 2 Plugin
===========================================
Reads the fomod.db file generated by FOMOD Plus and displays all known
FOMOD mods and their options in a searchable, collapsible web interface.

Features:
- Reads fomod.db (JSON) produced by FOMOD+ at <MO2>/fomod.db
- Hierarchical view: Mods -> Steps -> Groups -> Options
- Expand/collapse individual mods or all at once
- Search by mod name, step, group, or option name
- Filter by selection state (Selected / Available / Deselected)
- Filter by type pattern (Required / Recommended / Optional / NotUsable)
- "Find patches for mod X": searches ALL options across ALL mods in the DB
  for ones whose name contains the search term (case-insensitive)
- Auto-detects fomod.db in multiple locations (cwd, basePath, pluginsPath)
- Web server with dynamic port (8080-8089)
- Internationalization (i18n) via JSON files in MO2's translations/ folder
- No external dependencies (pure Python + embedded HTML)

Requirements:
- FOMOD Plus plugin installed (fomod_plus_installer.dll)
- fomod.db file (created by FOMOD+ when you install any mod with FOMOD)

Installation:
  1. Drop this file in MO2's plugins folder (alongside FOMOD Plus DLL).
  2. (Optional) Copy the translation files from the translations/ folder of
     this plugin's distribution into <MO2>/translations/. The plugin will
     auto-detect the user's MO2 language and load the matching JSON file.
     If no matching file exists, English is used as fallback.

Supported languages (out of the box):
  - English (en) - default/fallback
  - Spanish (es)
  - More can be added by dropping fomod_db_explorer_<lang>.json into
    <MO2>/translations/.

The plugin is generic and works with any MO2 instance regardless of where
MO2 itself or the instance data is installed.
"""

