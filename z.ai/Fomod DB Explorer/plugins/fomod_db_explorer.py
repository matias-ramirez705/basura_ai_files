    def _is_our_server_running(self, port: int) -> bool:
        try:
            req = urllib.request.Request(f'http://127.0.0.1:{port}/ping', method='GET')
            with urllib.request.urlopen(req, timeout=1.0) as resp:
                body = resp.read().decode('utf-8', errors='ignore')
                return 'FOMOD_DB_EXPLORER' in body
        except Exception:
            return False

    def _start_web_server(self) -> None:
        if self._server_started:
            return

        # Read the configured port from MO2 settings.
        # 0 = automatic port selection (try 8080, 8081, ..., 8089)
        # 1-65535 = try that specific port, fall back to auto if it's taken by a non-our process
        configured_port = self._get_int_setting('web_server_port', 0)
        self._debug_log(f"[WEB] Configured port setting: {configured_port}")

        chosen = None
        if configured_port and 1 <= configured_port <= 65535:
            # User wants a specific port - try it first
            sock = socket.socket(socket.AF_INET, socket.SOCK_STREAM)
            sock.setsockopt(socket.SOL_SOCKET, socket.SO_REUSEADDR, 1)
            try:
                sock.bind(('127.0.0.1', configured_port))
                sock.close()
                chosen = configured_port
                self._debug_log(f"[WEB] Using configured port {chosen}")
            except OSError:
                sock.close()
                # Check if it's our own server already running
                if self._is_our_server_running(configured_port):
                    self._debug_log(f"[WEB] Port {configured_port} already running our server - reusing")
                    self._server_started = True
                    self._server_port = configured_port
                    return
                self._debug_log(f"[WEB] Configured port {configured_port} is taken by another process - falling back to auto")

        # Auto port selection (either because configured_port is 0, or the configured port was taken)
        if chosen is None:
            start_port = configured_port if (configured_port and 1 <= configured_port <= 65535) else 8080
            # If the configured port was taken, try the NEXT 9 ports after it
            # Otherwise (configured_port == 0), try 8080-8089
            for offset in range(10):
                port = start_port + offset
                if port > 65535:
                    break
                sock = socket.socket(socket.AF_INET, socket.SOCK_STREAM)
                sock.setsockopt(socket.SOL_SOCKET, socket.SO_REUSEADDR, 1)
                try:
                    sock.bind(('127.0.0.1', port))
                    sock.close()
                    chosen = port
                    break
                except OSError:
                    sock.close()
                    if self._is_our_server_running(port):
                        self._debug_log(f"[WEB] Port {port} already running our server - reusing")
                        self._server_started = True
                        self._server_port = port
                        return
                    continue
            else:
                self._debug_log(f"[WEB] FATAL: no free port in range {start_port}-{start_port+9}")
                return
            self._debug_log(f"[WEB] Auto-selected port {chosen}")

        try:
            def run_server():
                handler = self._create_request_handler()
                class ReusableServer(socketserver.ThreadingTCPServer):
                    allow_reuse_address = True
                    daemon_threads = True
                # Store the httpd instance on self so we can shut it down later
                # when the idle monitor detects no browser is connected.
                self._httpd = ReusableServer(("127.0.0.1", chosen), handler)
                self._httpd.serve_forever()
            t = threading.Thread(target=run_server, daemon=True)
            t.start()
            self._server_started = True
            self._server_port = chosen
            # Reset heartbeat so the idle monitor gives the browser time to load
            self._last_heartbeat = datetime.now()
            self._debug_log(f"[WEB] Server started on port {chosen}")

            try:
                auto_open = self._organizer.pluginSetting(self.name(), "auto_open_browser")
            except Exception:
                auto_open = False
            if auto_open:
                import time
                time.sleep(0.5)
                webbrowser.open(f"http://127.0.0.1:{chosen}")

            # Start the idle-shutdown monitor (only if the user enabled it)
            self._start_heartbeat_monitor()
        except Exception as e:
            self._debug_log(f"[WEB] EXCEPTION: {e}")
            import traceback
            self._debug_log(traceback.format_exc())

    def _start_heartbeat_monitor(self) -> None:
        """Start a background thread that monitors browser heartbeats.
        If no heartbeat is received within the configured timeout, the server
        is shut down to free resources (the user closed the browser tab).
        The monitor only runs if 'auto_shutdown_when_idle' is True.
        """
        auto_shutdown = self._get_bool_setting('auto_shutdown_when_idle', True)
        if not auto_shutdown:
            self._debug_log("[HEARTBEAT] auto_shutdown_when_idle=False — monitor not started")
            return

        timeout = self._get_int_setting('idle_shutdown_timeout', 60)
        # Clamp timeout to a reasonable range (minimum 30s to avoid premature shutdown
        # during page refreshes; maximum 3600s = 1 hour)
        timeout = max(30, min(3600, timeout))

        def monitor():
            import time
            check_interval = 10  # check every 10 seconds
            self._debug_log(f"[HEARTBEAT] Monitor started (timeout={timeout}s, check every {check_interval}s)")
            while self._server_started:
                time.sleep(check_interval)
                if not self._server_started:
                    break
                if self._last_heartbeat is None:
                    # No heartbeat yet — could be the grace period right after server start.
                    # Reset it to now so we don't shut down prematurely.
                    self._last_heartbeat = datetime.now()
                    continue
                elapsed = (datetime.now() - self._last_heartbeat).total_seconds()
                if elapsed > timeout:
                    self._debug_log(f"[HEARTBEAT] No heartbeat for {elapsed:.0f}s (timeout={timeout}s) — shutting down server")
                    self._shutdown_server()
                    break
            self._debug_log("[HEARTBEAT] Monitor thread exiting")

        self._heartbeat_monitor_thread = threading.Thread(target=monitor, daemon=True)
        self._heartbeat_monitor_thread.start()

    def _shutdown_server(self) -> None:
        """Shut down the running web server and reset all server state.
        After this, display() can be called again to restart the server on-demand."""
        try:
            if self._httpd is not None:
                # shutdown() must be called from a different thread than serve_forever()
                self._httpd.shutdown()
                self._httpd.server_close()
                self._httpd = None
                self._debug_log("[WEB] Server shut down successfully")
            else:
                self._debug_log("[WEB] _shutdown_server called but no httpd instance")
        except Exception as e:
            self._debug_log(f"[WEB] Error during shutdown: {e}")
        finally:
            self._server_started = False
            self._server_port = None
            self._last_heartbeat = None

    def _create_request_handler(self):
        plugin_self = self

        class Handler(http.server.BaseHTTPRequestHandler):
            def do_GET(self):
                path_only = self.path.split('?', 1)[0]

                if path_only == '/ping':
                    self.send_response(200)
                    self.send_header('Content-type', 'application/json; charset=utf-8')
                    self.send_header('Cache-Control', 'no-store')
                    self.end_headers()
                    self.wfile.write(json.dumps({
                        'server': 'FOMOD_DB_EXPLORER',
                        'version': '3',
                        'port': plugin_self._server_port,
                    }).encode('utf-8'))
                    return

                if path_only.startswith('/active_plugins.json'):
                    # Return the set of active plugins (full names + base names)
                    # Used by Browse Mods to color master filenames green/red
                    active = plugin_self._get_active_plugins()
                    active_base = {plugin_self._strip_plugin_extension(p) for p in active}
                    self.send_response(200)
                    self.send_header('Content-type', 'application/json; charset=utf-8')
                    self.send_header('Cache-Control', 'no-store')
                    self.end_headers()
                    self.wfile.write(json.dumps({
                        'active': sorted(active),
                        'active_base': sorted(active_base),
                    }).encode('utf-8'))
                    return

                # /heartbeat endpoint — called by the browser every 20 seconds while
                # the page is open. Updates the last_heartbeat timestamp so the idle
                # monitor knows the browser is still active. If the user closes the
                # tab, heartbeats stop and the monitor shuts down the server.
                if path_only == '/heartbeat':
                    plugin_self._last_heartbeat = datetime.now()
                    self.send_response(200)
                    self.send_header('Content-type', 'application/json; charset=utf-8')
                    self.send_header('Cache-Control', 'no-store')
                    self.end_headers()
                    self.wfile.write(b'{"status":"ok"}')
                    return

                if path_only == '/' or path_only == '/index.html' or path_only == '':
                    self.send_response(200)
                    self.send_header('Content-type', 'text/html; charset=utf-8')
                    self.send_header('Cache-Control', 'no-store')
                    self.end_headers()
                    self.wfile.write(plugin_self._get_html().encode('utf-8'))
                    return

                if path_only.startswith('/data.json'):
                    self.send_response(200)
                    self.send_header('Content-type', 'application/json; charset=utf-8')
                    self.send_header('Cache-Control', 'no-store')
                    self.end_headers()
                    self.wfile.write(plugin_self._get_data_json().encode('utf-8'))
                    return

                if path_only.startswith('/summary.json'):
                    self.send_response(200)
                    self.send_header('Content-type', 'application/json; charset=utf-8')
                    self.send_header('Cache-Control', 'no-store')
                    self.end_headers()
                    self.wfile.write(json.dumps(plugin_self._get_db_summary(),
                                                indent=2, ensure_ascii=False).encode('utf-8'))
                    return

                if path_only.startswith('/patches.json'):
                    # Parse query string for ?q=...
                    from urllib.parse import urlparse, parse_qs
                    qs = parse_qs(urlparse(self.path).query)
                    q = qs.get('q', [''])[0]
                    self.send_response(200)
                    self.send_header('Content-type', 'application/json; charset=utf-8')
                    self.send_header('Cache-Control', 'no-store')
                    self.end_headers()
                    self.wfile.write(json.dumps(plugin_self._search_patches(q),
                                                indent=2, ensure_ascii=False).encode('utf-8'))
                    return

                if path_only.startswith('/i18n.json'):
                    # Return all translations + current language to the frontend
                    self.send_response(200)
                    self.send_header('Content-type', 'application/json; charset=utf-8')
                    self.send_header('Cache-Control', 'no-store')
                    self.end_headers()
                    self.wfile.write(json.dumps({
                        'language': plugin_self._language,
                        'strings': plugin_self._translations,
                    }, ensure_ascii=False).encode('utf-8'))
                    return

                if path_only.startswith('/reload'):
                    # Force re-detection of the DB path and reload
                    plugin_self._db_path = plugin_self._find_db_path()
                    summary = plugin_self._get_db_summary()
                    self.send_response(200)
                    self.send_header('Content-type', 'application/json; charset=utf-8')
                    self.send_header('Cache-Control', 'no-store')
                    self.end_headers()
                    self.wfile.write(json.dumps(summary,
                                                indent=2, ensure_ascii=False).encode('utf-8'))
                    return

                if path_only.startswith('/analyze_deps.json'):
                    # Run full dependency analysis (may take a few seconds)
                    report = plugin_self._analyze_dependencies()
                    self.send_response(200)
                    self.send_header('Content-type', 'application/json; charset=utf-8')
                    self.send_header('Cache-Control', 'no-store')
                    self.end_headers()
                    self.wfile.write(json.dumps(report,
                                                indent=2, ensure_ascii=False).encode('utf-8'))
                    return

                if path_only.startswith('/detect_patches.json'):
                    report = plugin_self._detect_patches_needed()
                    self.send_response(200)
                    self.send_header('Content-type', 'application/json; charset=utf-8')
                    self.send_header('Cache-Control', 'no-store')
                    self.end_headers()
                    self.wfile.write(json.dumps(report,
                                                indent=2, ensure_ascii=False).encode('utf-8'))
                    return

                if path_only.startswith('/export_guide.json'):
                    guide = plugin_self._export_guide()
                    self.send_response(200)
                    self.send_header('Content-type', 'application/json; charset=utf-8')
                    self.send_header('Cache-Control', 'no-store')
                    self.end_headers()
                    self.wfile.write(json.dumps(guide, indent=2, ensure_ascii=False).encode('utf-8'))
                    return

                if path_only.startswith('/toggle_mod_installed'):
                    from urllib.parse import urlparse, parse_qs
                    qs = parse_qs(urlparse(self.path).query)
                    mn = qs.get('mod', [''])[0]
                    inst = qs.get('installed', ['false'])[0].lower() == 'true'
                    ok = plugin_self._toggle_mod_installed(mn, inst)
                    self.send_response(200)
                    self.send_header('Content-type', 'application/json; charset=utf-8')
                    self.end_headers()
                    self.wfile.write(json.dumps({'success': ok}).encode('utf-8'))
                    return

                if path_only.startswith('/load_checkbox_state.json'):
                    state = plugin_self._load_checkbox_state()
                    self.send_response(200)
                    self.send_header('Content-type', 'application/json; charset=utf-8')
                    self.send_header('Cache-Control', 'no-store')
                    self.end_headers()
                    self.wfile.write(json.dumps(state, ensure_ascii=False).encode('utf-8'))
                    return

                if path_only.startswith('/dep_comments.json'):
                    # Return all user comments for the Dependency Analyzer
                    comments = plugin_self._load_comments()
                    self.send_response(200)
                    self.send_header('Content-type', 'application/json; charset=utf-8')
                    self.send_header('Cache-Control', 'no-store')
                    self.end_headers()
                    self.wfile.write(json.dumps(comments,
                                                ensure_ascii=False).encode('utf-8'))
                    return

                if path_only.startswith('/save_dep_comment'):
                    # This is a POST endpoint — redirect to do_POST
                    self.send_response(405)
                    self.send_header('Content-type', 'text/plain')
                    self.end_headers()
                    self.wfile.write(b'Method Not Allowed - use POST')
                    return

                self.send_response(404)
                self.send_header('Content-type', 'text/html')
                self.end_headers()
                self.wfile.write(b'<h1>404 Not Found</h1>')

            def do_POST(self):
                """Handle POST requests (currently only /save_dep_comment)."""
                path_only = self.path.split('?', 1)[0]
                if path_only.startswith('/save_dep_comment'):
                    content_length = int(self.headers.get('Content-Length', 0))
                    body = self.rfile.read(content_length).decode('utf-8') if content_length > 0 else ''
                    try:
                        data = json.loads(body)
                        mod_name = data.get('mod_name', '')
                        option_name = data.get('option_name', '')
                        comment = data.get('comment', '')
                        ok = plugin_self._save_comment(mod_name, option_name, comment)
                        self.send_response(200)
                        self.send_header('Content-type', 'application/json; charset=utf-8')
                        self.end_headers()
                        self.wfile.write(json.dumps({'success': ok}).encode('utf-8'))
                    except Exception as e:
                        self.send_response(500)
                        self.send_header('Content-type', 'application/json; charset=utf-8')
                        self.end_headers()
                        self.wfile.write(json.dumps({'success': False, 'error': str(e)}).encode('utf-8'))
                else:
                    self.send_response(404)
                    self.send_header('Content-type', 'text/html')
                    self.end_headers()
                    self.wfile.write(b'<h1>404 Not Found</h1>')

            def log_message(self, format, *args):
                pass

        return Handler

