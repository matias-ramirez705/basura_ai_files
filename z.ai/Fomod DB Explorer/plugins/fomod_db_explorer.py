    def _export_guide(self):
        from datetime import datetime
        guide = {'export_date': datetime.now().strftime("%Y-%m-%d %H:%M:%S"),
                 'plugin_version': '3', 'profile_name': '',
                 'active_plugins_count': 0, 'mods': []}
        try:
            try: guide['profile_name'] = self._organizer.profileName() or ''
            except Exception: pass
            active = self._get_active_plugins()
            ab = {self._strip_plugin_extension(p) for p in active}
            guide['active_plugins_count'] = len(active)
            comments = self._load_comments()
            cbs = self._load_checkbox_state()
            for mod in self._load_db():
                mn = mod.get('displayName', '')
                entry = {'mod_name': mn, 'mod_id': mod.get('modId'),
                         'installed': cbs.get(mn, False), 'options': []}
                for opt in mod.get('options', []):
                    ms = opt.get('masters', [])
                    ss = opt.get('selectionState', 'Available')
                    aok = all(self._is_master_active(m, active, ab) for m in ms) if ms else True
                    st = 'missing' if (ms and not aok) else ('selected_ok' if ss == 'Selected' else 'unselected_ok')
                    ck = f"{mn}::{opt.get('name', '')}"
                    entry['options'].append({'name': opt.get('name', ''), 'step': opt.get('step', ''),
                                              'group': opt.get('group', ''), 'selection_state': ss,
                                              'masters': ms, 'all_masters_active': aok,
                                              'status': st, 'comment': comments.get(ck, '')})
                guide['mods'].append(entry)
        except Exception as e:
            import traceback
            self._debug_log(f"[GUIDE] Export error: {e}")
            self._debug_log(traceback.format_exc())
            guide['error'] = str(e)
        return guide

    def _load_checkbox_state(self):
        d = self._get_guide_dir()
        if not d: return {}
        f = d / "checkbox_state.json"
        if not f.exists(): return {}
        try:
            with open(f, 'r', encoding='utf-8') as fh: return json.load(fh)
        except Exception: return {}

    def _save_checkbox_state(self, state):
        d = self._get_guide_dir()
        if not d: return False
        try:
            with open(d / "checkbox_state.json", 'w', encoding='utf-8') as f:
                json.dump(state, f, indent=2, ensure_ascii=False)
            return True
        except Exception: return False

    def _toggle_mod_installed(self, mod_name, installed):
        state = self._load_checkbox_state()
        state[mod_name] = installed
        return self._save_checkbox_state(state)

