    def _get_setting(self, key: str, default: Any = None) -> Any:
        """Read a plugin setting from MO2's plugin settings store.
        Returns the default value if MO2 is not available or the setting is missing.
        """
        if self._organizer is None:
            return default
        try:
            val = self._organizer.pluginSetting(self.name(), key)
            # MO2 may return values as strings or their native type depending on the setting
            return val if val is not None else default
        except Exception:
            return default

    def _get_bool_setting(self, key: str, default: bool = False) -> bool:
        """Read a boolean plugin setting. Handles string 'true'/'false' as well as
        native bool values (MO2 sometimes stores booleans as strings)."""
        val = self._get_setting(key, default)
        if isinstance(val, bool):
            return val
        if isinstance(val, str):
            return val.strip().lower() in ('true', '1', 'yes', 'on')
        if isinstance(val, (int, float)):
            return bool(val)
        return default

    def _get_int_setting(self, key: str, default: int = 0) -> int:
        """Read an integer plugin setting. Returns default on any parse error."""
        val = self._get_setting(key, default)
        try:
            return int(val)
        except (ValueError, TypeError):
            return default

    def _get_string_setting(self, key: str, default: str = '') -> str:
        """Read a string plugin setting."""
        val = self._get_setting(key, default)
        return str(val) if val is not None else default

    def init(self, organizer: mobase.IOrganizer) -> bool:
        self._organizer = organizer
        self._debug_log_path = Path(self._organizer.basePath()) / "fomod_db_explorer_debug.txt"
        self._debug_log("=" * 60)
        self._debug_log("[INIT] FOMOD DB Explorer init() called")
        self._debug_log(f"[INIT] basePath() = {self._organizer.basePath()}")
        self._debug_log(f"[INIT] cwd() = {Path.cwd()}")

        # Load translations (i18n) based on MO2's configured language
        self._load_translations()
        self._debug_log(f"[INIT] Loaded language: {self._language} ({len(self._translations)} strings)")

        # Find the DB file
        self._db_path = self._find_db_path()
        if self._db_path is None:
            self._debug_log("[INIT] WARNING: fomod.db not found yet - will retry when user opens the tool")
        else:
            self._debug_log(f"[INIT] Found fomod.db: {self._db_path.name}")
            self._debug_log(f"[INIT] DB size: {self._db_path.stat().st_size:,} bytes")

        # Start the web server — but only if the user opted in to "start on MO2 startup".
        # Default is False: the server starts on-demand when the user opens the plugin
        # via Tools -> FOMOD DB Explorer (see display()).
        start_on_startup = self._get_bool_setting('start_server_on_mo2_startup', False)
        if start_on_startup:
            self._debug_log("[INIT] start_server_on_mo2_startup=True — starting server now")
            self._start_web_server()
        else:
            self._debug_log("[INIT] start_server_on_mo2_startup=False — server will start on-demand when user opens the plugin")
        return True

