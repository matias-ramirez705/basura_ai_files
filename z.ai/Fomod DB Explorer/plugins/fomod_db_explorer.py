    def _get_comments_path(self) -> Optional[Path]:
        """Get the path to the comments JSON file for the active profile.
        Stored in: <basePath>/profiles/<profileName>/FOMOD DB Explorer/comments.json
        """
        try:
            base = Path(self._organizer.basePath())
            profile_name = None
            try:
                profile_name = self._organizer.profileName()
            except Exception:
                pass
            if not profile_name:
                try:
                    import configparser
                    ini_path = base / "ModOrganizer.ini"
                    if ini_path.exists():
                        cfg = configparser.ConfigParser()
                        cfg.read(ini_path, encoding='utf-8')
                        for section in ['Settings', 'General']:
                            if section in cfg and 'selected_profile' in cfg[section]:
                                profile_name = Path(cfg[section]['selected_profile']).name
                                break
                except Exception:
                    pass
            if not profile_name:
                return None
            comments_dir = base / "profiles" / profile_name / "FOMOD DB Explorer"
            comments_dir.mkdir(parents=True, exist_ok=True)
            return comments_dir / "comments.json"
        except Exception as e:
            self._debug_log(f"[COMMENTS] Error getting comments path: {e}")
            return None

    def _load_comments(self) -> Dict[str, str]:
        """Load all comments from the comments JSON file.
        Returns a dict keyed by '{mod_name}::{option_name}' → comment text.
        """
        comments_path = self._get_comments_path()
        if comments_path is None or not comments_path.exists():
            return {}
        try:
            with open(comments_path, 'r', encoding='utf-8') as f:
                data = json.load(f)
            if isinstance(data, dict):
                return data
        except Exception as e:
            self._debug_log(f"[COMMENTS] Error loading: {e}")
        return {}

    def _save_comment(self, mod_name: str, option_name: str, comment: str) -> bool:
        """Save or update a single comment. Empty comment deletes the entry.
        Key format: '{mod_name}::{option_name}'
        """
        try:
            comments_path = self._get_comments_path()
            if comments_path is None:
                return False
            comments = self._load_comments()
            key = f"{mod_name}::{option_name}"
            if comment and comment.strip():
                comments[key] = comment.strip()
            else:
                comments.pop(key, None)
            with open(comments_path, 'w', encoding='utf-8') as f:
                json.dump(comments, f, indent=2, ensure_ascii=False)
            self._debug_log(f"[COMMENTS] Saved comment for '{key}': '{comment[:50]}'")
            return True
        except Exception as e:
            self._debug_log(f"[COMMENTS] Error saving: {e}")
            return False

